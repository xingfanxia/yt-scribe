def entry(text):
    subs = sorted(set(re.findall(r"\$(\d)", text)))
    msg = re.sub(r"\$(\d)", lambda m: f"$P{m.group(1)}$", text)
    e = {"message": msg}
    if subs:
        e["placeholders"] = {f"p{n}": {"content": f"${n}"} for n in subs}
    return e

root = pathlib.Path(__file__).resolve().parent.parent / "_locales"
for idx, loc in enumerate(["en", "zh_CN"]):
    d = root / loc
    d.mkdir(parents=True, exist_ok=True)
    out = {k: entry(v[idx]) for k, v in M.items()}
    (d / "messages.json").write_text(json.dumps(out, ensure_ascii=False, indent=2) + "\n")
print(f"{len(M)} messages x 2 locales")
